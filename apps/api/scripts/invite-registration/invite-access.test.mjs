import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { fixture } from './test-support.mjs';
import { hashPassword } from '../../src/security.ts';
import { inviteAccessStatus } from '../../src/invite-access.ts';

test('access status preserves exact expiry and independent revocation semantics', () => {
  const now = Date.now();
  assert.equal(inviteAccessStatus({ expiresAt: new Date(now).toISOString() }, now), 'expired');
  assert.equal(inviteAccessStatus({ expiresAt: new Date(now + 1).toISOString() }, now), 'active');
  assert.equal(inviteAccessStatus({ expiresAt: 'invalid' }, now), 'expired');
  for (const field of ['disabledAt', 'revokedAt', 'deletedAt']) assert.equal(inviteAccessStatus({ expiresAt: new Date(now - 1).toISOString(), [field]: new Date(now).toISOString() }, now), 'disabled');
});

for (const kind of ['memory', 'postgres']) test(kind + ': activated invite access governs fresh login and existing sessions without affecting other actors', async t => {
  const f = await fixture(kind); t.after(() => f.close());
  if (f.db) {
    const indexes = await f.db.pool.query("select indexdef from pg_indexes where schemaname='auth' and indexname='registration_invites_used_by_idx'");
    assert.equal(indexes.rows.length, 1); assert.ok(!indexes.rows[0].indexdef.includes('UNIQUE')); assert.ok(indexes.rows[0].indexdef.includes('used_at IS NOT NULL'));
  }
  const owner = await f.actor('access-owner@example.com');
  const foreignOwner = await f.actor('access-foreign@example.com');
  const a = await f.actor('access-a@example.com', 'user');
  const b = await f.actor('access-b@example.com', 'user');
  const account = await f.runtime.store.createAccount({ adminId: a.id, platform: 'xianyu', sellerRef: 'shared-access-account' });
  await f.runtime.store.grantScope({ adminId: b.id, accountId: account.id, scope: 'read' });
  const sessionId = a.cookie.match(/session_id=([^;]+)/)[1];
  const action = (name, actor = owner, body = {}) => f.request(`/api/v1/auth/invites/${a.inviteId}/${name}`, { ...actor, method: 'POST', key: randomUUID(), body });
  const listed = async () => (await f.request('/api/v1/auth/invites', owner)).body.data.items.find(item => item.id === a.inviteId);
  const login = () => f.request('/api/v1/auth/password-login', { method: 'POST', body: { email: 'access-a@example.com', password: 'password-123' } });
  assert.equal((await listed()).status, 'used'); assert.equal((await listed()).accessStatus, 'active');
  assert.equal((await action('disable', foreignOwner)).status, 409);
  assert.equal((await action('disable', b)).status, 403);
  assert.equal((await listed()).accessStatus, 'active');
  const logoutLogin = await f.runtime.auth.login({ email: 'access-a@example.com', password: 'password-123' });
  const logoutActor = { cookie: `session_id=${logoutLogin.session.id}; csrf_token=${logoutLogin.csrfToken}`, csrf: logoutLogin.csrfToken };
  assert.equal((await action('disable')).status, 200);
  let row = await listed(); assert.equal(row.status, 'used'); assert.equal(row.accessStatus, 'disabled'); assert.equal(row.usedBy, a.id); assert.ok(row.usedAt);
  assert.equal((await login()).body.error.code, 'INVITE_ACCESS_DISABLED');
  assert.equal((await f.request('/api/v1/auth/session', a)).body.data.authenticated, false);
  assert.equal((await f.request('/api/v1/accounts', a)).status, 401);
  assert.equal((await f.request('/api/v1/auth/logout', { ...logoutActor, csrf: 'incorrect', method: 'POST', body: {} })).status, 403);
  assert.equal((await f.request('/api/v1/auth/logout', { ...logoutActor, method: 'POST', body: {} })).status, 200);
  assert.ok((await f.runtime.store.findSession(logoutLogin.session.id)).revokedAt);
  assert.equal((await f.request('/api/v1/settings/agent', { ...a, method: 'PATCH', key: randomUUID(), body: { accountId: account.id, expectedVersion: 0, maxLoops: 6 } })).status, 401);
  assert.equal((await f.request('/api/v1/accounts', owner)).status, 200);
  assert.equal((await f.request('/api/v1/accounts', b)).status, 200);
  assert.ok(await f.runtime.store.getAccount(b.id, account.id));
  assert.notEqual((await f.runtime.store.getAccount(b.id, account.id)).status, 'disabled');
  assert.equal((await action('renew', owner, { days: 30 })).status, 200);
  assert.equal((await listed()).accessStatus, 'disabled');
  assert.equal((await action('enable')).status, 200);
  assert.equal((await f.request('/api/v1/accounts', a)).status, 200, 'unexpired old sessions recover after enable');
  assert.equal((await f.request('/api/v1/accounts', logoutActor)).status, 401, 'explicit logout must never recover after enable');
  assert.equal((await login()).status, 200);
  const expiryLogoutLogin = await f.runtime.auth.login({ email: 'access-a@example.com', password: 'password-123' });
  const expiryLogoutActor = { cookie: `session_id=${expiryLogoutLogin.session.id}; csrf_token=${expiryLogoutLogin.csrfToken}`, csrf: expiryLogoutLogin.csrfToken };
  const before = (await f.runtime.store.findSession(sessionId)).lastSeenAt;
  await f.runtime.auth.accessFromSession(sessionId);
  await f.runtime.auth.accessFromSession(sessionId);
  assert.equal((await f.runtime.store.findSession(sessionId)).lastSeenAt, before, 'realtime checks must not keep idle sessions alive');
  await f.runtime.store.renewInvite(owner.id, a.inviteId, new Date(Date.now() - 1).toISOString());
  assert.equal((await listed()).accessStatus, 'expired');
  assert.equal((await login()).body.error.code, 'INVITE_ACCESS_EXPIRED');
  assert.equal((await f.request('/api/v1/accounts', a)).status, 401);
  assert.equal((await f.request('/api/v1/auth/logout', { ...expiryLogoutActor, method: 'POST', body: {} })).status, 200);
  assert.equal((await action('enable')).status, 200);
  assert.equal((await listed()).accessStatus, 'expired', 'enable must not extend expiry');
  assert.equal((await action('renew', owner, { days: 7 })).status, 200);
  assert.equal((await f.request('/api/v1/accounts', a)).status, 200);
  assert.equal((await f.request('/api/v1/accounts', expiryLogoutActor)).status, 401, 'explicit logout must never recover after renewal');
  row = await listed(); assert.equal(row.status, 'used'); assert.equal(row.usedBy, a.id); assert.equal(row.accessStatus, 'active');
  assert.equal((await f.request('/api/v1/auth/register', { method: 'POST', body: { inviteCode: a.inviteCode, email: 'access-reused@example.com', password: 'password-123', displayName: 'Reused' } })).status, 409);
  assert.equal(await f.runtime.store.findAdminByEmail('access-reused@example.com'), undefined);
  if (f.db) await f.db.pool.query('update auth.registration_invites set revoked_at=now() where id=$1', [a.inviteId]);
  else f.runtime.store.invites.get(a.inviteId).revokedAt = new Date().toISOString();
  assert.equal((await action('enable')).status, 200);
  assert.equal((await listed()).accessStatus, 'disabled', 'independent revocation survives enable');
  assert.equal((await f.request('/api/v1/accounts', a)).status, 401);
  const ungranted = await f.runtime.store.createAdmin({ email: 'ungranted@example.com', passwordHash: await hashPassword('password-123'), displayName: 'Ungrounded User', role: 'user' });
  await assert.rejects(() => f.runtime.auth.login({ email: ungranted.email, password: 'password-123' }), error => error.code === 'INVITE_ACCESS_MISSING');
});
